//! Poppler runs in a cancellable child process: no PDF parsing on the UI thread.
use sha2::{Digest, Sha256};
use std::{
    fs,
    io::{Read, Seek, SeekFrom},
    path::{Path, PathBuf},
    process::{Command, Stdio},
    sync::{
        atomic::{AtomicU64, Ordering},
        Arc,
    },
    time::{Duration, Instant, UNIX_EPOCH},
};

pub const PAGE_EDGE: u32 = 2400;
pub const THUMB_EDGE: u32 = 192;
// Includes reading-page PNGs and thumbnails; eviction occurs off the UI/render workers.
pub const DISK_BUDGET: u64 = 384 * 1024 * 1024;

/// Use coarse resolution steps to avoid rerendering for each tiny resize/zoom change.
pub fn edge_bucket(desired_pixels: f32) -> u32 {
    const BUCKETS: [u32; 8] = [512, 704, 896, 1152, 1408, 1728, 2048, PAGE_EDGE];
    let pixels = if desired_pixels.is_finite() {
        desired_pixels.max(1.0)
    } else {
        1152.0
    };
    BUCKETS
        .into_iter()
        .find(|&edge| edge as f32 >= pixels)
        .unwrap_or(PAGE_EDGE)
}

/// A clickable internal destination within one rendered PDF page.
/// Bounds are normalized to the page's displayed image (top-left origin).
#[derive(Clone, Debug, PartialEq)]
pub struct PdfLink {
    pub left: f32,
    pub top: f32,
    pub right: f32,
    pub bottom: f32,
    pub target_page: u32,
}

/// Read a Poppler XML attribute. Output is generated by pdftohtml, not user-authored XML.
fn xml_attr<'a>(tag: &'a str, name: &str) -> Option<&'a str> {
    let prefix = format!("{name}=\"");
    let rest = tag.get(tag.find(&prefix)? + prefix.len()..)?;
    rest.get(..rest.find('"')?)
}

fn internal_page(href: &str, total: u32) -> Option<u32> {
    let (file, fragment) = href.rsplit_once('#')?;
    // pdftohtml resolves PDF GoTo destinations to same-document .html#PAGE links.
    // Do not treat an external URL with a numeric anchor as a PDF page jump.
    if file.contains("://")
        || file.contains('/')
        || file.contains('\\')
        || (!file.is_empty() && !file.to_ascii_lowercase().ends_with(".html"))
    {
        return None;
    }
    let number = fragment.strip_prefix("page=").unwrap_or(fragment);
    number
        .parse::<u32>()
        .ok()
        .filter(|page| (1..=total).contains(page))
}

fn parse_page_links(xml: &str, page: u32, total: u32) -> Vec<PdfLink> {
    let mut links = Vec::new();
    let mut remaining = xml;
    while let Some(start) = remaining.find("<page ") {
        remaining = &remaining[start..];
        let Some(header_end) = remaining.find('>') else {
            break;
        };
        let header = &remaining[..header_end];
        let Some(end) = remaining.find("</page>") else {
            break;
        };
        let page_content = &remaining[header_end + 1..end];
        remaining = &remaining[end + "</page>".len()..];
        if xml_attr(header, "number").and_then(|v| v.parse::<u32>().ok()) != Some(page) {
            continue;
        }
        let width = xml_attr(header, "width").and_then(|v| v.parse::<f32>().ok());
        let height = xml_attr(header, "height").and_then(|v| v.parse::<f32>().ok());
        let (Some(width), Some(height)) = (width, height) else {
            break;
        };
        if !width.is_finite() || !height.is_finite() || width <= 0.0 || height <= 0.0 {
            break;
        }
        let page_left = xml_attr(header, "left")
            .and_then(|v| v.parse().ok())
            .unwrap_or(0.0);
        let page_top = xml_attr(header, "top")
            .and_then(|v| v.parse().ok())
            .unwrap_or(0.0);
        let mut text = page_content;
        while let Some(text_start) = text.find("<text ") {
            text = &text[text_start..];
            let Some(text_header_end) = text.find('>') else {
                break;
            };
            let Some(text_end) = text.find("</text>") else {
                break;
            };
            let text_header = &text[..text_header_end];
            let body = &text[text_header_end + 1..text_end];
            text = &text[text_end + "</text>".len()..];
            let coords = ["left", "top", "width", "height"]
                .map(|key| xml_attr(text_header, key).and_then(|v| v.parse::<f32>().ok()));
            let [Some(left), Some(top), Some(box_width), Some(box_height)] = coords else {
                continue;
            };
            let bounds = [
                ((left - page_left) / width).clamp(0.0, 1.0),
                ((top - page_top) / height).clamp(0.0, 1.0),
                ((left + box_width - page_left) / width).clamp(0.0, 1.0),
                ((top + box_height - page_top) / height).clamp(0.0, 1.0),
            ];
            if !bounds.iter().all(|n| n.is_finite())
                || bounds[2] <= bounds[0]
                || bounds[3] <= bounds[1]
            {
                continue;
            }
            let mut anchors = body;
            while let Some(anchor_start) = anchors.find("<a ") {
                anchors = &anchors[anchor_start..];
                let Some(anchor_header_end) = anchors.find('>') else {
                    break;
                };
                let anchor_header = &anchors[..anchor_header_end];
                anchors = &anchors[anchor_header_end + 1..];
                let Some(target_page) =
                    xml_attr(anchor_header, "href").and_then(|href| internal_page(href, total))
                else {
                    continue;
                };
                links.push(PdfLink {
                    left: bounds[0],
                    top: bounds[1],
                    right: bounds[2],
                    bottom: bounds[3],
                    target_page,
                });
            }
        }
        break;
    }
    links
}

/// Extract text-link hit areas and resolved page destinations on a worker thread.
/// Requires pdftohtml, supplied by the same Poppler suite as pdftoppm/pdfinfo.
pub fn page_links(
    path: &Path,
    page: u32,
    total: u32,
    generation: &Arc<AtomicU64>,
    expected: u64,
) -> Result<Vec<PdfLink>, String> {
    let mut command = Command::new(program("pdftohtml"));
    command.args([
        "-q",
        "-xml",
        "-noroundcoord",
        "-i",
        "-f",
        &page.to_string(),
        "-l",
        &page.to_string(),
        "-stdout",
    ]);
    command.arg(path);
    let bytes = execute(command, generation, expected)?;
    Ok(parse_page_links(
        &String::from_utf8_lossy(&bytes),
        page,
        total,
    ))
}

fn program(name: &str) -> PathBuf {
    // Optional explicit, trusted Poppler installation directory; never searched in the library.
    std::env::var_os("EDER_POPPLER_DIR")
        .or_else(|| std::env::var_os("FOLIO_POPPLER_DIR"))
        .map(PathBuf::from)
        .map(|p| {
            p.join(if cfg!(windows) {
                format!("{name}.exe")
            } else {
                name.into()
            })
        })
        .unwrap_or_else(|| name.into())
}
fn execute(
    mut command: Command,
    generation: &Arc<AtomicU64>,
    expected: u64,
) -> Result<Vec<u8>, String> {
    let mut out = tempfile::tempfile().map_err(|e| e.to_string())?;
    let mut err = tempfile::tempfile().map_err(|e| e.to_string())?;
    command
        .stdin(Stdio::null())
        .stdout(out.try_clone().map_err(|e| e.to_string())?)
        .stderr(err.try_clone().map_err(|e| e.to_string())?);
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        command.creation_flags(0x08000000);
    }
    let mut child = command.spawn().map_err(|e| {
        format!("Cannot start Poppler: {e}. Install pdfinfo and pdftoppm; see README.")
    })?;
    let start = Instant::now();
    loop {
        if generation.load(Ordering::Acquire) != expected
            || start.elapsed() > Duration::from_secs(30)
        {
            let _ = child.kill();
            let _ = child.wait();
            return Err("Rendering cancelled or exceeded 30 seconds.".into());
        }
        match child.try_wait() {
            Ok(Some(status)) => {
                if !status.success() {
                    let _ = err.seek(SeekFrom::Start(0));
                    let mut message = String::new();
                    let _ = err.take(4096).read_to_string(&mut message);
                    return Err(format!("Cannot open/render PDF: {}", message.trim()));
                }
                break;
            }
            Ok(None) => std::thread::sleep(Duration::from_millis(10)),
            Err(e) => {
                let _ = child.kill();
                let _ = child.wait();
                return Err(e.to_string());
            }
        }
    }
    out.seek(SeekFrom::Start(0)).map_err(|e| e.to_string())?;
    let mut bytes = Vec::new();
    // Bounded output: XML with many linked text fragments can exceed pdfinfo's size.
    const MAX_OUTPUT: u64 = 2 * 1024 * 1024;
    out.take(MAX_OUTPUT + 1)
        .read_to_end(&mut bytes)
        .map_err(|e| e.to_string())?;
    if bytes.len() as u64 > MAX_OUTPUT {
        return Err("PDF metadata exceeds the supported size.".into());
    }
    Ok(bytes)
}
pub fn page_count(path: &Path, generation: &Arc<AtomicU64>, expected: u64) -> Result<u32, String> {
    if !path.is_file() {
        return Err("This PDF is no longer available.".into());
    }
    let mut command = Command::new(program("pdfinfo"));
    command.env("LC_ALL", "C").arg(path);
    let bytes = execute(command, generation, expected)?;
    String::from_utf8_lossy(&bytes)
        .lines()
        .find_map(|l| {
            l.strip_prefix("Pages:")
                .and_then(|n| n.trim().parse::<u32>().ok())
        })
        .filter(|n| *n > 0)
        .ok_or_else(|| "The document has no readable pages.".into())
}
fn key(path: &Path) -> Result<String, String> {
    let m = fs::metadata(path).map_err(|e| e.to_string())?;
    let mut hash = Sha256::new();
    hash.update(path.as_os_str().as_encoded_bytes());
    hash.update(m.len().to_le_bytes());
    hash.update(
        m.modified()
            .map_err(|e| e.to_string())?
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos()
            .to_le_bytes(),
    );
    Ok(format!("{:x}", hash.finalize()))
}
fn decode(path: &Path) -> Result<image::RgbaImage, String> {
    let mut reader = image::ImageReader::open(path)
        .map_err(|e| e.to_string())?
        .with_guessed_format()
        .map_err(|e| e.to_string())?;
    let mut limits = image::Limits::default();
    limits.max_image_width = Some(PAGE_EDGE);
    limits.max_image_height = Some(PAGE_EDGE);
    limits.max_alloc = Some(64 * 1024 * 1024);
    reader.limits(limits);
    reader
        .decode()
        .map(|i| i.to_rgba8())
        .map_err(|e| e.to_string())
}
pub fn raster(
    path: &Path,
    page: u32,
    edge: u32,
    cache: &Path,
    generation: &Arc<AtomicU64>,
    expected: u64,
) -> Result<image::RgbaImage, String> {
    if !(1..=PAGE_EDGE).contains(&edge) || page == 0 {
        return Err("Invalid render dimensions or page.".into());
    }
    let thumb = edge == THUMB_EDGE && page == 1;
    // Cached reading pages are keyed by file fingerprint, page AND resolution.
    // The original thumbnail cache filename is preserved for backward compatibility.
    let cached = key(path).ok().map(|key| {
        if thumb {
            cache.join(format!("{key}.png"))
        } else {
            cache.join(format!("{key}-p{page}-e{edge}.png"))
        }
    });
    if let Some(p) = &cached {
        if let Ok(image) = decode(p) {
            return Ok(image);
        }
    }
    // Cache failure must never prevent viewing a document.
    let temp = tempfile::tempdir().map_err(|e| e.to_string())?;
    let prefix = temp.path().join("page");
    let mut command = Command::new(program("pdftoppm"));
    command
        .args([
            "-f",
            &page.to_string(),
            "-l",
            &page.to_string(),
            "-singlefile",
            "-scale-to",
            &edge.to_string(),
            "-png",
        ])
        .arg(path)
        .arg(&prefix);
    execute(command, generation, expected)?;
    let output = prefix.with_extension("png");
    let result = decode(&output)?;
    if let Some(p) = cached {
        if generation.load(Ordering::Acquire) == expected && fs::create_dir_all(cache).is_ok() {
            // Write a unique temporary file and atomically rename it into the cache.
            // Interrupted rendering never leaves a partial PNG at its final name.
            let temp_name = cache.join(format!(
                "{}.{}.tmp",
                p.file_name().unwrap_or_default().to_string_lossy(),
                std::process::id()
            ));
            if fs::copy(&output, &temp_name).is_ok() && fs::rename(&temp_name, &p).is_err() {
                // Windows cannot rename over a corrupt existing cache entry.
                let _ = fs::remove_file(&p);
                let _ = fs::rename(&temp_name, p);
            }
            let _ = fs::remove_file(temp_name);
        }
    }
    Ok(result)
}
pub fn trim_cache(cache: &Path, budget: u64) -> std::io::Result<()> {
    let mut files: Vec<_> = fs::read_dir(cache)?
        .filter_map(Result::ok)
        .filter(|e| e.path().extension().is_some_and(|e| e == "png"))
        .filter_map(|e| {
            e.metadata()
                .ok()
                .map(|m| (e.path(), m.len(), m.modified().ok()))
        })
        .collect();
    let mut total: u64 = files.iter().map(|f| f.1).sum();
    files.sort_by_key(|f| f.2);
    for (p, size, _) in files {
        if total <= budget {
            break;
        }
        if fs::remove_file(p).is_ok() {
            total = total.saturating_sub(size);
        }
    }
    Ok(())
}

#[cfg(test)]
mod link_tests {
    use super::*;

    #[test]
    fn poppler_internal_link_text_resolves_pages_and_rectangles() {
        let xml = r##"<pdf2xml>
<page number="1" top="0" left="0" width="900" height="1200">
<text top="180" left="90" width="180" height="24"><a href="book.html#2">Chapter 2</a></text>
<text top="230" left="90" width="180" height="24"><a href="book.html#3">Chapter 3</a></text>
<text top="300" left="90" width="180" height="24"><a href="https://example.com#4">External</a></text>
</page></pdf2xml>"##;
        let links = parse_page_links(xml, 1, 3);
        assert_eq!(links.len(), 2);
        assert_eq!(links[0].target_page, 2);
        assert!((links[0].left - 0.1).abs() < 0.00001);
        assert!((links[0].top - 0.15).abs() < 0.00001);
        assert_eq!(links[1].target_page, 3);
        assert!(parse_page_links(xml, 2, 3).is_empty());
        assert_eq!(parse_page_links(xml, 1, 2).len(), 1);
    }

    #[test]
    fn raster_buckets_limit_repeated_work() {
        assert_eq!(edge_bucket(850.0), 896);
        assert_eq!(edge_bucket(851.0), 896);
        assert_eq!(edge_bucket(4000.0), PAGE_EDGE);
        assert_eq!(edge_bucket(f32::NAN), 1152);
    }

    #[test]
    fn rejects_invalid_destinations_and_bounds() {
        assert_eq!(internal_page("guide.html#page=12", 12), Some(12));
        assert_eq!(internal_page("guide.html#0", 12), None);
        assert_eq!(internal_page("guide.html#13", 12), None);
        assert_eq!(internal_page("https://example.com/path#3", 12), None);
        let xml = r##"<page number="2" width="0" height="500"><text left="2" top="1" width="3" height="3"><a href="#1">Item</a></text></page>"##;
        assert!(parse_page_links(xml, 2, 5).is_empty());
    }
}
